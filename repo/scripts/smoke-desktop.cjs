process.env.WORDBOOK_SMOKE_TEST = '1';
const { app, ipcMain, Menu, dialog } = require('electron');
const version = require('../package.json').version;
const build = require('../src/manifest.json').versionCode;
const fs = require('node:fs/promises');
const path = require('node:path');
const assert = require('node:assert/strict');
const { ready, getWindow, paths } = require('../electron/main.cjs');
const output = paths.reports;
const wait = () => new Promise(resolve => setTimeout(resolve, 150));
const checks = [];
async function run() {
  await ready;
  const win = getWindow(), web = win.webContents;
  assert.equal(paths.userData, path.resolve(__dirname, '../../dist/.cache/desktop-smoke-data'));
  const logs = [];
  web.on('console-message', (_event, _level, message) => logs.push(message));
  const text = () => web.executeJavaScript('document.body.innerText');
  async function click(label) {
    for (let i = 0; i < 30; i++) { if ((await text()).includes(label)) break; await wait(); }
    const found = await web.executeJavaScript(`(() => { const button=[...document.querySelectorAll('uni-button')].find(b=>b.textContent.trim().startsWith(${JSON.stringify(label)}));if(!button)return false;button.click();return true;})()`);
    assert.ok(found, '没有找到按钮 ' + label); await wait();
  }
  const files = await web.executeJavaScript('window.wordbookDesktop.listInput()');
  assert.ok(files.includes('导入示例.xlsx')); checks.push('Electron preload 与 dist/input 扫描可用');
  await web.executeJavaScript(`localStorage.clear()`); await web.reload();
  await new Promise(resolve => web.once('did-finish-load', resolve));
  await click('先用示例体验'); await click('开始背诵 →');
  assert.match(await text(), /bloom/);
  await web.executeJavaScript('document.querySelector(".flashcard").click()'); await wait();
  assert.match(await text(), /The cherry trees bloom in spring/); checks.push('卡片翻转显示词义、音标、例句');
  await click('✓ 已记住，隐藏'); assert.match(await text(), /1 \/ 5/); checks.push('隐藏当前单词后轮询减为 5 词');
  await click('隐藏词 1'); await click('恢复为生词'); assert.match(await text(), /还没有隐藏的单词/); checks.push('隐藏词恢复生词');
  const card = () => web.executeJavaScript('({word:document.querySelector(".card-word").textContent,position:document.querySelector(".study-controls>.muted").textContent})');
  await click('← 返回背诵'); await click('下一个 →'); const alpha = await card();
  await click('← 我的单词本'); await click('继续背诵 →'); assert.deepEqual(await card(), alpha);
  await click('⇄ 完全乱序'); await click('下一个 →'); const random = await card();
  await click('A–Z 字母顺序'); assert.deepEqual(await card(), alpha);
  await click('⇄ 完全乱序'); assert.deepEqual(await card(), random);
  checks.push('离开再进入续背，两种排序分别保留位置与乱序队列');
  await web.reload(); await new Promise(resolve => web.once('did-finish-load', resolve));
  await click('继续背诵 →'); assert.deepEqual(await card(), random);
  assert.equal(await web.executeJavaScript('document.querySelector(".study-controls .selected").textContent.trim()'), '⇄ 完全乱序');
  checks.push('重新加载后恢复上次排序与当前卡片');
  await web.executeJavaScript(`Object.defineProperty(window,'speechSynthesis',{configurable:true,value:{cancel(){},speak(utterance){setTimeout(()=>utterance.onend?.(),20)}}});true`);
  const beforePlay = (await card()).word;
  await click('开始连播');
  for (let i = 0; i < 35 && (await card()).word === beforePlay; i++) await wait();
  assert.notEqual((await card()).word, beforePlay);
  await click('暂停连播'); const paused = await card();
  await new Promise(resolve => setTimeout(resolve, 3300)); assert.deepEqual(await card(), paused);
  checks.push('连播等待发音结束和间隔再切词，暂停后保持当前位置');
  await click('A–Z 字母顺序');
  await click('搜索与编辑词条');
  assert.equal(await web.executeJavaScript('getComputedStyle(document.querySelector(".modal")).backgroundColor'), 'rgb(255, 255, 255)');
  await click('新增词条');
  async function fill(selector, value) {
    await web.executeJavaScript(`(() => { const input=document.querySelector(${JSON.stringify(selector)});if(!input)throw Error('Missing input');input.value=${JSON.stringify(value)};input.dispatchEvent(new Event('input',{bubbles:true}));})()`); await wait();
  }
  await fill('.entry-editor input', 'zoology'); await fill('.entry-editor textarea', '动物学');
  await click('保存词条'); await fill('.modal .name-input input', 'zoology');
  assert.match(await text(), /动物学/);
  await fs.mkdir(output, { recursive: true });
  await fs.writeFile(path.join(output, 'word-manager-preview.png'), (await web.capturePage()).toPNG());
  await click('跳转背诵'); assert.equal((await card()).word, 'zoology');
  checks.push('新增、中文释义搜索与跳转背诵');
  await click('✓ 已记住，隐藏'); await click('继续查看'); await click('撤销隐藏');
  assert.equal((await card()).word, 'zoology');
  await click('下一个 →'); assert.match(await text(), /本轮已完成/); await click('继续查看');
  await web.executeJavaScript(`document.body.dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowLeft',bubbles:true}))`); await wait();
  assert.notEqual((await card()).word, 'zoology');
  await web.executeJavaScript(`document.body.dispatchEvent(new KeyboardEvent('keydown',{code:'Space',bubbles:true}))`); await wait();
  assert.ok(await web.executeJavaScript('!!document.querySelector(".flashcard.flipped")'));
  checks.push('撤销隐藏、队尾完成不循环、键盘切词与翻面');
  await click('⚙　基础设置'); await click('本地恢复点');
  assert.match(await text(), /修改前/); await web.executeJavaScript('document.querySelector("[aria-label=关闭恢复点]").click()'); await wait();
  checks.push('编辑前自动创建本地恢复点');
  let exported;
  ipcMain.removeHandler('backup:save');
  ipcMain.handle('backup:save', (_event, _name, value) => { exported = value; return true; });
  await click('导出全部数据');
  const incoming = JSON.parse(exported); assert.equal(incoming.books.length, 1); assert.ok(incoming.exportedAt);
  incoming.books[0].name = '备份中的示例本'; incoming.books[0].entries[0].status = 'hidden';
  await click('＋　导入单词本'); await click('粘贴 JSON 恢复');
  await fill('.paste-area textarea', JSON.stringify(incoming)); await click('检查内容');
  assert.match(await text(), /隐藏状态变化 1/);
  assert.ok(await web.executeJavaScript(`([...document.querySelectorAll('uni-button')].find(b=>b.textContent.trim()==='确认所选恢复方式')).hasAttribute('disabled')`));
  await click('使用备份覆盖'); await click('确认所选恢复方式');
  assert.match(await text(), /备份中的示例本/); checks.push('完整 JSON 导出、恢复差异及显式覆盖选择');
  await click('＋　导入单词本');
  async function importFixture(name) {
    const bytes = Array.from(await fs.readFile(path.resolve(__dirname, '../../dist/input', name)));
    // 开发测试注入本地 File 对象，避免自动化弹出操作系统选择器。
    await web.executeJavaScript(`(() => { document.querySelector('.import-panel uni-button').click(); const input=document.querySelector('input[type=file]');const dt=new DataTransfer();dt.items.add(new File([new Uint8Array(${JSON.stringify(bytes)})],${JSON.stringify(name)}));input.files=dt.files;input.dispatchEvent(new Event('change'));})()`);
    for (let i = 0; i < 100; i++) { await wait(); if (/检查导入内容|Review import/.test(await text())) return; }
    throw Error('文件预览未出现：' + name + '\n' + (await text()).slice(-500));
  }
  await importFixture('导入示例.xlsx');
  assert.match(await text(), /选中 3 条/); checks.push('本地 Excel 文件解析与脏数据默认剔除');
  await click('创建单词本');
  await click('＋　导入单词本');
  const pdfFixture = files.find(name => /^俞敏洪托福单词.*\.pdf$/i.test(name));
  assert.ok(pdfFixture, '输入目录缺少托福 PDF 检查资料');
  await importFixture(pdfFixture);
  assert.ok(await web.executeJavaScript(`[...document.querySelectorAll('.preview-fields input')].some(input=>input.value==='a range of')`)); checks.push('file 协议下 PDF Worker 正常解析双栏源文件');
  await web.executeJavaScript('document.querySelector(".modal-heading .icon-btn").click()'); await wait();
  await click('▤　我的单词本');
  await fs.mkdir(output, { recursive: true });
  await fs.writeFile(path.join(output, 'desktop-preview.png'), (await web.capturePage()).toPNG());
  const help = Menu.getApplicationMenu().items.find(item => item.role === 'help');
  assert.equal(help.label, '帮助');
  assert.ok(help?.submenu.items.find(item => item.label === '关于拾词'));
  const originalDialog = dialog.showMessageBox;
  let about;
  dialog.showMessageBox = async (_window, options) => { about = options; return { response: 0 }; };
  try { await help.submenu.items.find(item => item.label === '关于拾词').click(); }
  finally { dialog.showMessageBox = originalDialog; }
  assert.ok(about.detail.includes('版本 ' + version)); checks.push('Windows Help → 关于拾词显示当前应用版本');
  await click('帮助'); assert.ok((await text()).includes('版本 ' + version)); assert.ok((await text()).includes('构建号 ' + build));
  await fs.writeFile(path.join(output, 'about-desktop.png'), (await web.capturePage()).toPNG());
  win.setContentSize(390, 844); await wait();
  assert.ok(await web.executeJavaScript('document.querySelector(".top-actions uni-button").getBoundingClientRect().width > 0'));
  assert.ok(await web.executeJavaScript('document.documentElement.scrollWidth <= window.innerWidth'));
  await fs.writeFile(path.join(output, 'about-mobile.png'), (await web.capturePage()).toPNG());
  checks.push('帮助页在桌面和手机宽度显示版本与构建号，无横向溢出');
  assert.equal(await web.executeJavaScript('document.querySelector(".sidebar-bottom .version")'), null);
  await click('⚙　基础设置');
  const storedBooks = await web.executeJavaScript('localStorage.getItem("wordbook.v1")');
  await click('English');
  assert.match(await text(), /Interface language/);
  assert.equal(Menu.getApplicationMenu().items.find(item => item.role === 'help').label, 'Help');
  assert.equal(await web.executeJavaScript('localStorage.getItem("wordbook.v1")'), storedBooks);
  await web.reload(); await new Promise(resolve => web.once('did-finish-load', resolve)); await wait();
  assert.match(await text(), /My wordbooks/);
  await click('Help'); assert.ok((await text()).includes('Version ' + version));
  assert.ok(!(await text()).includes('帮助与关于'));
  assert.ok(await web.executeJavaScript('document.documentElement.scrollWidth <= window.innerWidth'));
  await fs.writeFile(path.join(output, 'about-mobile-en.png'), (await web.capturePage()).toPNG());
  checks.push('中英切换同步 Windows 菜单，重载记住语言，单词本数据不变且角落无版本号');
  await click('⚙ Settings'); await click('Export all data');
  await click('＋ Import'); await click('Paste JSON');
  await fill('.paste-area textarea', exported); await click('Review content');
  assert.match(await text(), /Compare & restore backup/);
  assert.match(await text(), /Keep local/);
  await web.executeJavaScript(`document.querySelector('[aria-label="Cancel backup restore"]').click()`); await wait();
  await importFixture('导入示例.xlsx');
  assert.match(await text(), /Missing definition|Duplicate word/);
  await web.executeJavaScript(`document.querySelector('[aria-label="Close preview"]').click()`); await wait();
  await click('▤ My books'); await click('Find & edit words');
  assert.ok(await web.executeJavaScript(`!!document.querySelector('uni-input[aria-label="Search words or definitions"]')`));
  await click('Add word'); await click('Save word'); assert.match(await text(), /Word cannot be empty/);
  await web.executeJavaScript(`document.querySelector('[aria-label="Close word manager"]').click()`); await wait();
  await click('⚙ Settings'); await click('中文'); assert.match(await text(), /基础设置/);
  checks.push('英文导入警告、备份比较、词条编辑错误及切回中文正常');
  await fs.writeFile(path.join(output, 'desktop-smoke.json'), JSON.stringify({ passed: true, checks, logs }, null, 2));
  console.log(JSON.stringify({ passed: true, checks }, null, 2));
  app.quit();
}
run().catch(async error => { console.error(error); await fs.mkdir(output, { recursive: true }); const html = await getWindow()?.webContents.executeJavaScript('document.body.innerHTML'); await fs.writeFile(path.join(output, 'desktop-smoke.json'), JSON.stringify({ passed: false, error: error.stack, html }, null, 2)); app.exit(1); });
