import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
if (process.platform !== 'win32') throw Error('请在 Windows x64 环境生成便携版');
const require = createRequire(import.meta.url);
const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dist = path.resolve(repo, '../dist');
const output = path.join(dist, 'desktop');
const electronDir = path.join(path.dirname(require.resolve('electron/package.json')), 'dist');
await fs.access(path.join(dist, 'web/index.html'));
await fs.access(path.join(electronDir, 'electron.exe'));
await fs.mkdir(output, { recursive: true });
// 只更新 desktop 中的程序；用户 input、data 和 backups 均位于上一级。
await fs.cp(electronDir, output, { recursive: true });
await fs.copyFile(path.join(output, 'electron.exe'), path.join(output, 'Wordbook.exe'));
await fs.unlink(path.join(output, 'electron.exe'));
const appDir = path.join(output, 'resources/app');
await fs.mkdir(appDir, { recursive: true });
await fs.cp(path.join(repo, 'electron'), path.join(appDir, 'electron'), { recursive: true });
await fs.writeFile(path.join(appDir, 'package.json'), JSON.stringify({ name: 'wordbook', version: '0.1.0', main: 'electron/main.cjs' }, null, 2));
await fs.cp(path.join(dist, 'web'), path.join(output, 'resources/web'), { recursive: true });
await fs.mkdir(path.join(dist, 'input'), { recursive: true });
await fs.mkdir(path.join(dist, 'backups'), { recursive: true });
await fs.copyFile(path.join(repo, 'scripts/dist-layout.md'), path.join(dist, 'README.md'));
await fs.writeFile(path.join(output, '使用说明.txt'), '\ufeff拾词 Wordbook\r\n双击本目录 Wordbook.exe 启动，无需安装。请保留整个 desktop 文件夹的运行库。\r\nExcel/PDF 放在上一级 input 文件夹，在软件中选择“导入单词本 → 扫描 dist/input”。\r\n单词本与隐藏状态保存在上一级 data 文件夹；导出备份默认保存到上一级 backups 文件夹。\r\n迁移个人数据时请一并复制 desktop、data；如需源资料，再复制 input。\r\n对外共享程序只需 desktop 文件夹，不要附带个人 data、input 或 backups。\r\n');
console.log('Windows 便携版已生成：' + path.join(output, 'Wordbook.exe'));
