export function translate(message, language = 'zh', params = {}) {
  const source = String(message ?? '');
  let translated = language === 'en' ? (en[source] ?? source) : source;
  if (language === 'en' && !Object.hasOwn(en, source)) {
    for (const prefix of ['导出失败：', '无法打开系统保存窗口：']) {
      if (source.startsWith(prefix)) { translated = en[prefix] + source.slice(prefix.length); break; }
    }
  }
  return translated.replace(/\{(\w+)\}/g, (match, key) => Object.hasOwn(params, key) ? String(params[key]) : match);
}
